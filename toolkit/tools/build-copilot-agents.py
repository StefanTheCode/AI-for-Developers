"""
Build GitHub Copilot editions of the toolkit agents.

Source of truth:  toolkit/agents/*.md                 (Claude Code format)
                  packs/dotnet/agents/*.md            (Claude Code format)
Output:           toolkit/copilot/agents/*.agent.md
                  packs/dotnet/copilot/agents/*.agent.md   (the .NET pack agents + the legacy pair from the toolkit)

The instructions (Markdown body) are copied unchanged. Only the frontmatter is
rewritten: Copilot tool names, and no model / category / version fields.

Run from the repo root after you change any agent:
    python toolkit/tools/build-copilot-agents.py
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "toolkit" / "agents"
SRC_DOTNET = ROOT / "packs" / "dotnet" / "agents"
OUT_ALL = ROOT / "toolkit" / "copilot" / "agents"
OUT_LEGACY = ROOT / "packs" / "dotnet" / "copilot" / "agents"
LEGACY_AGENTS = {"legacy-modernization-assistant", "framework-upgrade-agent"}

# Claude Code tool name -> Copilot tool alias
TOOL_MAP = {
    "read": "read", "notebookread": "read",
    "edit": "edit", "multiedit": "edit", "write": "edit", "notebookedit": "edit",
    "grep": "search", "glob": "search",
    "bash": "execute", "powershell": "execute",
    "webfetch": "web", "websearch": "web",
    "task": "agent",
    "todowrite": "todo",
}

FRONTMATTER = re.compile(r"^---\r?\n(.*?)\r?\n---\r?\n(.*)$", re.S)


def parse_frontmatter(text: str, path: Path):
    m = FRONTMATTER.match(text)
    if not m:
        sys.exit(f"{path}: no frontmatter")
    fields = {}
    for line in m.group(1).splitlines():
        key, sep, value = line.partition(":")
        if sep:
            fields[key.strip()] = value.strip()
    for required in ("name", "description"):
        if not fields.get(required):
            sys.exit(f"{path}: missing '{required}'")
    return fields, m.group(2)


def copilot_tools(claude_tools: str):
    tools = []
    for t in (x.strip() for x in claude_tools.split(",")):
        if not t:
            continue
        mapped = TOOL_MAP.get(t.lower())
        if mapped is None:
            sys.exit(f"Unknown tool '{t}' - add it to TOOL_MAP")
        if mapped not in tools:
            tools.append(mapped)
    return tools


def build(path: Path, src_rel: str) -> str:
    fields, body = parse_frontmatter(path.read_text(encoding="utf-8"), path)
    desc = fields["description"].replace("\\", "\\\\").replace('"', '\\"')
    lines = ["---", f"name: {fields['name']}", f'description: "{desc}"']
    if fields.get("tools"):
        tools = ", ".join(f"'{t}'" for t in copilot_tools(fields["tools"]))
        lines.append(f"tools: [{tools}]")
    lines.append("---")
    note = (f"<!-- GitHub Copilot edition of {src_rel}/{path.name}. "
            "Generated by toolkit/tools/build-copilot-agents.py - edit the original, then re-run the script. -->")
    return "\n".join(lines) + "\n\n" + note + "\n\n" + body.lstrip("\n")


def main():
    OUT_ALL.mkdir(parents=True, exist_ok=True)
    OUT_LEGACY.mkdir(parents=True, exist_ok=True)
    count = 0
    for path in sorted(SRC_DOTNET.glob("*.md")) if SRC_DOTNET.exists() else []:
        out = OUT_LEGACY / f"{path.stem}.agent.md"
        out.write_text(build(path, "packs/dotnet/agents"), encoding="utf-8", newline="\n")
        print(f"  {out.relative_to(ROOT)}")
        count += 1
    for path in sorted(SRC.glob("*.md")):
        content = build(path, "toolkit/agents")
        targets = [OUT_ALL]
        if path.stem in LEGACY_AGENTS:
            targets.append(OUT_LEGACY)
        for folder in targets:
            out = folder / f"{path.stem}.agent.md"
            out.write_text(content, encoding="utf-8", newline="\n")
            print(f"  {out.relative_to(ROOT)}")
        count += 1
    print(f"Built {count} Copilot agents.")


if __name__ == "__main__":
    main()
